var update = flag.Bool("update", false, "write web/src/types/messages.gen.ts anew from the ui_ messages")

const messagesGen = "web/src/types/messages.gen.ts"

// TestMessagesGen keeps the keys the management page's TypeScript may name those of the ui_ messages: the type
// MessageKey, written from the English catalog.
func TestMessagesGen(t *testing.T) {
	t.Parallel()

	var b bytes.Buffer
	b.WriteString("// Code generated by go test ./internal/ui -run TestMessagesGen -update; DO NOT EDIT.\n\nexport type MessageKey =\n")
	for _, key := range slices.Sorted(func(yield func(string) bool) {
		for key := range i18n.EnglishCatalog().Formats("ui_") {
			if !yield(key) {
				return
			}
		}
	}) {
		b.WriteString("  | '" + key + "'\n")
	}
	b.WriteString(";\n")
	if *update {
		if err := os.WriteFile(messagesGen, b.Bytes(), 0o644); err != nil { //nolint:gosec // a file of the repository
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(messagesGen)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, b.Bytes()) {
		t.Errorf("%s is not the ui_ messages: run go test ./internal/ui -run TestMessagesGen -update and commit it", messagesGen)
	}
}

// webSources reads the management page's TypeScript under web/src but its tests, by their path under web/src.
func webSources(t *testing.T) map[string]string {
	t.Helper()

	sources := map[string]string{}
	root := os.DirFS("web/src")
	err := fs.WalkDir(root, ".", func(name string, d fs.DirEntry, err error) error {
		switch {
		case err != nil:
			return err
		case d.IsDir():
			return nil
		}
		ext := path.Ext(name)
		if (ext != ".ts" && ext != ".tsx") || strings.HasSuffix(name, ".test"+ext) {
			return nil
		}
		b, err := fs.ReadFile(root, name)
		sources[name] = string(b)
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	if len(sources) == 0 {
		t.Fatal("read no source under web/src")
	}
	return sources
}

// namedIn are the sources of web/src that hold text, sorted.
func namedIn(sources map[string]string, text string) []string {
	var in []string
	for name, src := range sources {
		if strings.Contains(src, text) {
			in = append(in, name)
		}
	}
	slices.Sort(in)
	return in
}

// TestFetchInApiClient keeps every request of the management page in lib/api-client.ts, whose api counts the writes
// a read of the list waits for, and which looks window.fetch up at each call, as the browser tests replace it.
// LIMIT: the text .fetch( alone is looked for: window["fetch"], const { fetch } = window or Reflect.get pass. Read the
// TypeScript's tree if one of them comes to be written.
func TestFetchInApiClient(t *testing.T) {
	t.Parallel()

	if got, want := namedIn(webSources(t), ".fetch("), []string{"lib/api-client.ts"}; !slices.Equal(got, want) {
		t.Errorf(".fetch( is named in %v, want %v", got, want)
	}
}

var gallery = flag.String("gallery", "", "write web/gallery/boot.json, the gallery's boot values, in this language (ja, en)")

// TestGalleryBoot is no test: with -gallery it writes the boot values the gallery is served with (just web-gallery), a
// file .gitignore leaves out, of the list screen in that language.
func TestGalleryBoot(t *testing.T) {
	t.Parallel()

	if *gallery == "" {
		t.Skip("writes web/gallery/boot.json with -gallery only")
	}
	lang := i18n.Lang(*gallery)
	if !slices.Contains(i18n.Langs(), lang) {
		t.Fatalf("-gallery=%s: not a language of floe's: %v", *gallery, i18n.Langs())
	}
	b, err := json.Marshal(newBoot(i18n.New(lang), List, "", false, ""))
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile("web/gallery/boot.json", b, 0o644); err != nil { //nolint:gosec // a file of the repository
		t.Fatal(err)
	}
}
